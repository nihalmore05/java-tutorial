package Loops.While_Loop_example;


// Q1) Print numbers from 10 to 1 using a while loop.


public class num_print {
    public static void main(String[] args){

        int num = 10;

        while(num >= 1){
            // System.out.println("Hello Nihal");
            System.out.println(num);
            num --;
        }
    }
    
}
